#!/usr/bin/env node
/**
 * Helpers for the local Supabase (Docker) used to try a branch's SQL without touching develop.
 *
 *   node scripts/local-db.mjs env            point the app at the local database
 *   node scripts/local-db.mjs off            point the app back at develop
 *   node scripts/local-db.mjs apply <files>  run SQL files on the local database
 *   node scripts/local-db.mjs users          create the local test users
 *   node scripts/local-db.mjs pull           copy develop's structure (no data) and rebuild the local database
 *
 * Every command refuses to run unless the target is local, so it can never write to develop.
 */

import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ENV_FILE = resolve('.env.development.local');
const BASELINE = 'supabase/migrations/20261020000000_develop_baseline.sql';
const MARKER = '# Generated by scripts/local-db.mjs';

/** Local-only test accounts. The passwords exist only in the local database. */
const TEST_USERS = [
	{ username: 'superadmin', password: 'local-superadmin', role: 'Superadmin', name: 'Super', last_name: 'Admin' },
	{ username: 'admin', password: 'local-admin', role: 'Admin', name: 'Admin', last_name: 'Local' },
	{ username: 'taller', password: 'local-taller', role: 'Taller', name: 'Taller', last_name: 'Local' },
	{ username: 'qr', password: 'local-qr', role: 'QR', name: 'QR', last_name: 'Local' },
];

function fail(message) {
	console.error(`\n✖ ${message}\n`);
	process.exit(1);
}

function projectId() {
	const config = readFileSync(resolve('supabase/config.toml'), 'utf8');
	return config.match(/^project_id\s*=\s*"([^"]+)"/m)?.[1] ?? fail('No project_id in supabase/config.toml');
}

/** Reads the running local stack's URL and keys from the Supabase CLI. */
function localStatus() {
	let output;
	try {
		output = execFileSync('supabase', ['status', '-o', 'env'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
	} catch (error) {
		if (error.code === 'ENOENT') fail('Falta la CLI de Supabase: brew install supabase/tap/supabase');
		fail('El Supabase local no está corriendo. Abrí Docker Desktop y corré "npm run db:start".');
	}

	const values = Object.fromEntries(
		output
			.split('\n')
			.map((line) => line.match(/^([A-Z_]+)="?([^"]*)"?$/))
			.filter(Boolean)
			.map(([, key, value]) => [key, value])
	);

	const status = {
		url: values.API_URL,
		anonKey: values.ANON_KEY ?? values.PUBLISHABLE_KEY,
		serviceKey: values.SERVICE_ROLE_KEY ?? values.SECRET_KEY,
	};

	if (!status.url || !status.anonKey || !status.serviceKey) fail('No pude leer las claves de "supabase status".');
	assertLocal(status.url);
	return status;
}

function assertLocal(url) {
	const { hostname } = new URL(url);
	if (!['localhost', '127.0.0.1', '[::1]'].includes(hostname)) {
		fail(`"${url}" no es local. Este script solo trabaja con el Supabase de Docker.`);
	}
}

function writeEnv() {
	const { url, anonKey, serviceKey } = localStatus();

	if (existsSync(ENV_FILE) && !readFileSync(ENV_FILE, 'utf8').startsWith(MARKER)) {
		fail('.env.development.local ya existe y no lo generó este script. Revisalo antes de pisarlo.');
	}

	// Only the Supabase variables change; mail, push and the rest keep coming from .env.development.
	writeFileSync(
		ENV_FILE,
		[
			MARKER,
			'# Points the app at the local Supabase. Remove it with "npm run db:off".',
			`NEXT_PUBLIC_SUPABASE_URL=${url}`,
			`NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}`,
			`SUPABASE_SERVICE_ROLE_KEY=${serviceKey}`,
			`SUPABASE_URL=${url}`,
			'',
		].join('\n')
	);
	console.log(`✔ La app ahora usa el Supabase local (${url}). Reiniciá "npm run dev".`);
}

function removeEnv() {
	if (!existsSync(ENV_FILE)) {
		console.log('✔ La app ya usa develop.');
		return;
	}
	if (!readFileSync(ENV_FILE, 'utf8').startsWith(MARKER)) {
		fail('.env.development.local no lo generó este script; no lo borro.');
	}
	rmSync(ENV_FILE);
	console.log('✔ La app vuelve a usar develop. Reiniciá "npm run dev".');
}

/** Runs SQL inside the local database container, so nothing else needs psql installed. */
function applySql(files) {
	if (files.length === 0) fail('Indicá qué archivo correr, por ejemplo: npm run db:apply -- schema-supabase/users/user-views.sql');

	const container = `supabase_db_${projectId()}`;

	for (const file of files) {
		const path = resolve(file);
		if (!existsSync(path)) fail(`No existe ${file}`);

		console.log(`→ ${file}`);
		const result = spawnSync(
			'docker',
			['exec', '-i', container, 'psql', '-U', 'postgres', '-d', 'postgres', '-v', 'ON_ERROR_STOP=1', '-q'],
			{ input: readFileSync(path), stdio: ['pipe', 'inherit', 'inherit'] }
		);

		if (result.error) fail(`No pude usar Docker: ${result.error.message}`);
		if (result.status !== 0) fail(`Falló ${file}. La base local quedó como estaba antes de ese archivo.`);
	}
	console.log('✔ SQL aplicado en la base local.');
}

async function seedUsers() {
	const { url, serviceKey } = localStatus();
	const headers = { apikey: serviceKey, Authorization: `Bearer ${serviceKey}`, 'Content-Type': 'application/json' };

	const request = async (path, options = {}) => {
		const response = await fetch(`${url}${path}`, { ...options, headers: { ...headers, ...options.headers } });
		const body = await response.json().catch(() => null);
		if (!response.ok) throw new Error(body?.msg ?? body?.message ?? body?.error_description ?? response.statusText);
		return body;
	};

	const { users: existing = [] } = await request('/auth/v1/admin/users?per_page=1000');

	for (const user of TEST_USERS) {
		const email = `${user.username}@local.test`;
		const found = existing.find((candidate) => candidate.email === email);

		// Re-running keeps the same accounts and resets their passwords.
		const authUser = found
			? await request(`/auth/v1/admin/users/${found.id}`, { method: 'PUT', body: JSON.stringify({ password: user.password }) })
			: await request('/auth/v1/admin/users', {
					method: 'POST',
					body: JSON.stringify({ email, password: user.password, email_confirm: true }),
				});

		try {
			await request('/rest/v1/users?on_conflict=username', {
				method: 'POST',
				headers: { Prefer: 'resolution=merge-duplicates' },
				body: JSON.stringify({
					username: user.username,
					role: user.role,
					uid_user: authUser.id,
					mail: email,
					name: user.name,
					last_name: user.last_name,
				}),
			});
		} catch (error) {
			fail(`No pude crear "${user.username}" en public.users (${error.message}). ¿Está aplicada la estructura base?`);
		}

		console.log(`✔ ${user.username.padEnd(11)} ${user.role.padEnd(11)} contraseña: ${user.password}`);
	}
}

/** Reads a line in raw mode without echoing a single character, so a secret never shows on screen. */
function askHidden(question) {
	return new Promise((resolvePromise) => {
		const { stdin, stdout } = process;
		stdout.write(question);

		// Piped input (not a terminal) has no echo to hide.
		if (!stdin.isTTY) {
			let buffer = '';
			stdin.setEncoding('utf8');
			stdin.on('data', (chunk) => (buffer += chunk));
			stdin.on('end', () => resolvePromise(buffer.split('\n')[0].trim()));
			return;
		}

		let answer = '';
		stdin.setRawMode(true);
		stdin.resume();
		stdin.setEncoding('utf8');

		const onData = (chunk) => {
			for (const char of chunk) {
				if (char === '\r' || char === '\n') {
					stdin.setRawMode(false);
					stdin.pause();
					stdin.off('data', onData);
					stdout.write('\n');
					resolvePromise(answer.trim());
					return;
				}
				if (char === '\u0003') {
					stdin.setRawMode(false);
					stdout.write('\n');
					process.exit(130);
				}
				if (char === '\u007f' || char === '\b') answer = answer.slice(0, -1);
				else answer += char;
			}
		};
		stdin.on('data', onData);
	});
}

function run(commandName, commandArgs) {
	const result = spawnSync(commandName, commandArgs, { stdio: 'inherit' });
	if (result.error?.code === 'ENOENT') fail(`Falta ${commandName}.`);
	if (result.status !== 0) fail(`Falló: ${commandName} ${commandArgs[0]}`);
}

/**
 * Copies develop's structure (tables, functions, policies; never data) into a migration,
 * then rebuilds the local database from it, seeds users and points the app at it.
 */
async function pullDevelop(template) {
	let dbUrl;

	if (template?.includes('[YOUR-PASSWORD]')) {
		// The dashboard's string comes with a placeholder: only the password is asked for.
		console.log('Escribí la contraseña de la base de develop y apretá Enter.');
		console.log('No se muestra en pantalla ni se guarda en ningún archivo.\n');
		const password = await askHidden('Contraseña: ');
		if (!password) fail('No escribiste ninguna contraseña.');
		dbUrl = template.replace('[YOUR-PASSWORD]', encodeURIComponent(password));
	} else {
		console.log('Pegá la dirección de conexión de develop (Supabase → Connect → Direct → Session pooler).');
		console.log('No se muestra en pantalla ni se guarda en ningún archivo.\n');
		dbUrl = await askHidden('Dirección: ');
	}

	if (!/^postgres(ql)?:\/\//.test(dbUrl)) fail('Eso no parece una dirección de Postgres (empieza con postgresql://).');
	if (/@(localhost|127\.0\.0\.1)[:/]/.test(dbUrl)) fail('Esa dirección es local; tiene que ser la de develop.');

	console.log('\n→ Copiando la estructura de develop (solo lectura, sin datos)...');
	run('supabase', ['db', 'dump', '--db-url', dbUrl, '-f', BASELINE]);

	console.log('\n→ Armando la base local desde cero...');
	run('supabase', ['db', 'reset']);

	await seedUsers();
	writeEnv();
	console.log('\n✔ Listo. Corré "npm run dev" y entrá con superadmin, admin, taller o qr.');
}

const [command, ...args] = process.argv.slice(2);

const commands = {
	env: writeEnv,
	off: removeEnv,
	apply: () => applySql(args),
	users: seedUsers,
	pull: () => pullDevelop(args[0]),
};

if (!commands[command]) fail(`Comando desconocido "${command ?? ''}". Usá: env, off, apply, users o pull.`);

await commands[command]();
