create table public.checklists (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  work_id bigint not null,
  description text null,
  name text null,
  type_furniture text null,
  width numeric(10, 2) null,
  height numeric(10, 2) null,
  notes text null,
  depth numeric(10, 2) null,
  constraint checklists_pkey primary key (id),
  constraint checklists_work_id_fkey foreign KEY (work_id) references works (id) on update CASCADE on delete CASCADE
) TABLESPACE pg_default;

ALTER TABLE public.checklists ENABLE ROW LEVEL SECURITY;

