CREATE OR REPLACE FUNCTION public.withholdings_check_payment_expense() RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path = public AS $$
BEGIN
  IF NEW.payment_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.payments p WHERE p.id = NEW.payment_id AND p.expense_id = NEW.expense_id) THEN
    RAISE EXCEPTION 'El pago no corresponde al gasto de la retención';
  END IF;
  RETURN NEW;
END; $$;
DROP TRIGGER IF EXISTS trg_withholdings_check_payment_expense ON public.withholdings;
CREATE TRIGGER trg_withholdings_check_payment_expense BEFORE INSERT OR UPDATE OF payment_id, expense_id ON public.withholdings FOR EACH ROW EXECUTE FUNCTION public.withholdings_check_payment_expense();
