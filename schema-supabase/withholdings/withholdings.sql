CREATE OR REPLACE FUNCTION public.withholdings_compute_amounts() RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path = public AS $$
BEGIN NEW.withheld_amount := round(NEW.imputed_amount * NEW.rate, 2); RETURN NEW; END; $$;
