CREATE OR REPLACE FUNCTION public.create_payment_with_withholding(p_date date, p_receipt_number text, p_work_id bigint, p_category_id bigint, p_description text, p_amount numeric, p_payment_method_id bigint, p_bank_account_id bigint, p_expense_id bigint, p_tax_regime text, p_rate numeric, p_imputed_amount numeric, p_period text DEFAULT NULL, p_notes text DEFAULT NULL)
RETURNS public.payments LANGUAGE plpgsql SECURITY INVOKER SET search_path = public AS $$
DECLARE v_payment public.payments;
BEGIN
  IF p_expense_id IS NULL THEN RAISE EXCEPTION 'La retención requiere un gasto'; END IF;
  IF p_tax_regime IS NULL OR btrim(p_tax_regime) = '' THEN RAISE EXCEPTION 'El régimen de la retención es obligatorio'; END IF;
  INSERT INTO public.payments (date, receipt_number, work_id, category_id, description, amount, payment_method_id, bank_account_id, expense_id)
  VALUES (p_date, p_receipt_number, p_work_id, p_category_id, p_description, p_amount, p_payment_method_id, p_bank_account_id, p_expense_id) RETURNING * INTO v_payment;
  INSERT INTO public.withholdings (expense_id, payment_id, date, period, tax_regime, imputed_amount, rate, notes)
  VALUES (p_expense_id, v_payment.id, p_date, COALESCE(p_period, to_char(p_date, 'YYYY-MM')), btrim(p_tax_regime), p_imputed_amount, p_rate, p_notes);
  RETURN v_payment;
END; $$;
REVOKE ALL ON FUNCTION public.create_payment_with_withholding(date, text, bigint, bigint, text, numeric, bigint, bigint, bigint, text, numeric, numeric, text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.create_payment_with_withholding(date, text, bigint, bigint, text, numeric, bigint, bigint, bigint, text, numeric, numeric, text, text) TO authenticated;
COMMIT;


