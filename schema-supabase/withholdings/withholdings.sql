DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'withholdings' AND column_name = 'base')
     AND NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'withholdings' AND column_name = 'imputed_amount') THEN
    ALTER TABLE public.withholdings RENAME COLUMN base TO imputed_amount;
  END IF;
  IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'withholdings' AND column_name = 'amount')
     AND NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'withholdings' AND column_name = 'withheld_amount') THEN
    ALTER TABLE public.withholdings RENAME COLUMN amount TO withheld_amount;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'withholdings_base_chk')
     AND NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'withholdings_imputed_amount_chk') THEN
    ALTER TABLE public.withholdings RENAME CONSTRAINT withholdings_base_chk TO withholdings_imputed_amount_chk;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'withholdings_amount_chk')
     AND NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'withholdings_withheld_amount_chk') THEN
    ALTER TABLE public.withholdings RENAME CONSTRAINT withholdings_amount_chk TO withholdings_withheld_amount_chk;
  END IF;
END $$;
