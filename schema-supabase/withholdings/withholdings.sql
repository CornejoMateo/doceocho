CREATE TABLE IF NOT EXISTS public.withholdings (
  id         bigint generated by default as identity primary key,
  expense_id bigint not null references public.expenses(id) on delete restrict,
  date       date not null,
  period     text not null,
  tax_regime text null,
  base       numeric not null,
  rate       numeric not null,
  amount     numeric not null,
  notes      text null,
  created_at timestamptz not null default now(),
  constraint withholdings_period_format_chk
    check (period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  constraint withholdings_base_chk   check (base >= 0),
  constraint withholdings_rate_chk   check (rate >= 0 and rate <= 1),
  constraint withholdings_amount_chk check (amount >= 0),
  constraint withholdings_notes_len_chk check (notes is null or char_length(notes) <= 2000)
);

CREATE INDEX IF NOT EXISTS withholdings_expense_id_idx ON public.withholdings (expense_id);
CREATE INDEX IF NOT EXISTS withholdings_date_idx       ON public.withholdings (date);
CREATE INDEX IF NOT EXISTS withholdings_period_idx     ON public.withholdings (period);

ALTER TABLE public.withholdings ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Admin select withholdings" ON public.withholdings;
CREATE POLICY "Admin select withholdings"
  ON public.withholdings FOR SELECT TO authenticated
  USING (EXISTS (
    SELECT 1 FROM public.users u
    WHERE u.uid_user = auth.uid() AND public.is_admin_role(u.role)
  ));

CREATE OR REPLACE FUNCTION public.withholdings_require_supplier()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM public.expenses e
    WHERE e.id = NEW.expense_id AND e.supplier_id IS NOT NULL
  ) THEN
    RAISE EXCEPTION 'No se puede registrar una retención sobre un gasto sin proveedor';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_withholdings_require_supplier ON public.withholdings;
CREATE TRIGGER trg_withholdings_require_supplier
  BEFORE INSERT OR UPDATE OF expense_id ON public.withholdings
  FOR EACH ROW EXECUTE FUNCTION public.withholdings_require_supplier();

