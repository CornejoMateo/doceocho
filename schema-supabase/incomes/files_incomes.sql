CREATE TABLE IF NOT EXISTS public.files_incomes (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  storage_path text not null,
  income_id bigint not null,
  file_name text null,
  description text null,
  constraint files_incomes_pkey primary key (id),
  constraint files_incomes_storage_path_key unique (storage_path),
  constraint files_incomes_income_id_fkey foreign key (income_id) references public.incomes (id) on update cascade on delete cascade,
  constraint files_incomes_description_length_check check (description is null or char_length(description) <= 200)
) TABLESPACE pg_default;

------ INDEXES ------

CREATE INDEX IF NOT EXISTS files_incomes_income_id_idx ON public.files_incomes (income_id);

------ RLS ------

ALTER TABLE public.files_incomes ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public select files_incomes" ON public.files_incomes;
CREATE POLICY "Public select files_incomes"
ON public.files_incomes
FOR SELECT
TO authenticated
USING (
    EXISTS (
        SELECT 1
        FROM public.users u
        WHERE u.uid_user = auth.uid()
            AND public.is_admin_role(u.role)
    )
);

