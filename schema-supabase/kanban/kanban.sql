------ Kanban cards Table -------

CREATE TABLE IF NOT EXISTS kanban_cards (
    id bigint generated by default as identity not null,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    list_id BIGINT NOT NULL REFERENCES kanban_lists(id) ON DELETE CASCADE,
    title text NOT NULL,
    description TEXT,
    position INTEGER DEFAULT 0,
    due_date TIMESTAMPTZ,
    priority VARCHAR(20) DEFAULT 'none' CHECK (priority IN ('none', 'low', 'medium', 'high', 'very_high')),
    completed_at TIMESTAMPTZ,
);

CREATE INDEX idx_cards_list_position ON kanban_cards(list_id, position);

CREATE POLICY "kanban_cards insert"
ON public.kanban_cards
FOR INSERT
TO authenticated
WITH CHECK (
    EXISTS (
        SELECT 1
        FROM public.users u
        WHERE u.uid_user = auth.uid()
          AND u.role = 'Admin'
    )
);

CREATE POLICY "kanban_cards update"
ON public.kanban_cards
FOR UPDATE
TO authenticated
USING (    
  (EXISTS ( SELECT 1
   FROM (kanban_board_members kbm
     JOIN kanban_lists kl ON ((kl.board_id = kbm.board_id)))
  WHERE ((kl.id = kanban_cards.list_id) AND (kbm.user_id = auth.uid()))))
) 
WITH CHECK (
  (EXISTS ( SELECT 1
   FROM (kanban_board_members kbm
     JOIN kanban_lists kl ON ((kl.board_id = kbm.board_id)))
  WHERE ((kl.id = kanban_cards.list_id) AND (kbm.user_id = auth.uid()))))
);

CREATE POLICY "kanban_cards select"
ON public.kanban_cards
FOR SELECT
TO authenticated
USING (
    EXISTS (
        SELECT 1
        FROM public.kanban_board_members kbm
        JOIN public.kanban_lists kl ON kl.board_id = kbm.board_id
        WHERE kl.id = kanban_cards.list_id
          AND kbm.user_id = auth.uid()
    )
);

CREATE POLICY "kanban_cards delete"
