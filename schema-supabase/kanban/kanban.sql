------ RPC Function to create a board and add the creator as a member -------

create or replace function public.create_board_with_member(
    p_name text,
    p_description text,
    p_color text default '#4F5C4D'
)
returns json
language plpgsql
as $$
declare
    v_board_id bigint;
    v_user_id uuid;
begin
    v_user_id := auth.uid();

    insert into public.kanban_boards (
        name,
        description,
        color
    )
    values (
        p_name,
        p_description,
        p_color
    )
    returning id into v_board_id;

    insert into public.kanban_board_members (
        board_id,
        user_id
    )
    values (
        v_board_id,
        v_user_id
    );

    return json_build_object(
        'id', v_board_id,
        'name', p_name,
        'description', p_description,
        'color', p_color
    );
end;
$$;

------- Kanban Boards Table -------

CREATE TABLE IF NOT EXISTS kanban_boards (
    id bigint generated by default as identity not null,
    name text NOT NULL,
    description TEXT,
    color VARCHAR(7) DEFAULT '#4F5C4D',
    due_date_tolerance_yellow INTEGER DEFAULT 2, -- Days before due date to show yellow warning
    due_date_tolerance_red INTEGER DEFAULT 0 -- Days before due date to show red warning (0 = only on due date)
);

CREATE POLICY "kanban_boards insert"
ON public.kanban_boards
FOR INSERT
TO authenticated
WITH CHECK (
    EXISTS (
        SELECT 1
        FROM public.users u
        WHERE u.uid_user = auth.uid()
          AND u.role = 'Admin'
    )
);

