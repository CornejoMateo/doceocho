------- Files payments table ------

CREATE TABLE IF NOT EXISTS public.files_payments (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  storage_path text not null,
  payment_id bigint not null,
  file_name text null,
  description text null,
  constraint files_payments_pkey primary key (id),
  constraint files_payments_storage_path_key unique (storage_path),
  constraint files_payments_payment_id_fkey foreign key (payment_id) references public.payments (id) on update cascade on delete cascade,
  constraint files_payments_description_length_check check (description is null or char_length(description) <= 200)
) TABLESPACE pg_default;

------ INDEXES ------

CREATE INDEX IF NOT EXISTS files_payments_payment_id_idx ON public.files_payments (payment_id);

------ RLS ------

ALTER TABLE public.files_payments ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public select files_payments" ON public.files_payments;
CREATE POLICY "Public select files_payments"
ON public.files_payments
FOR SELECT
TO authenticated
USING (
    EXISTS (
        SELECT 1
        FROM public.users u
        WHERE u.uid_user = auth.uid()
            AND public.is_admin_role(u.role)
    )
);

