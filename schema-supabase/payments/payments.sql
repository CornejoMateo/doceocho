------- PAYMENTS TABLE -------
-- General payments only (no supplier). Supplier payments always live in payments_suppliers.
-- CREATE TABLE/INDEX: solo instalaciones nuevas.

create table public.payments (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  date date not null,
  receipt_number text null,
  work_id bigint null,
  category_id bigint null,
  kind text not null default 'payment',
  description text null,
  amount numeric not null,
  payment_method_id bigint not null,
  bank_account_id bigint null,
  constraint payments_pkey primary key (id),
  constraint payments_kind_check check (kind = 'payment'),
  constraint payments_work_id_fkey foreign key (work_id) references public.works (id) on delete set null,
  constraint payments_category_id_kind_fkey foreign key (category_id, kind) references public.cash_flow_categories (id, kind) on delete set null,
  constraint payments_payment_method_id_fkey foreign key (payment_method_id) references public.payment_methods (id) on delete restrict,
  constraint payments_bank_account_id_fkey foreign key (bank_account_id) references public.bank_accounts (id) on delete set null,
  constraint payments_receipt_number_length_check check (receipt_number is null or char_length(receipt_number) <= 60),
  constraint payments_description_length_check check (description is null or char_length(description) <= 300),
  constraint payments_amount_check check (amount > 0),
  constraint payments_amount_decimals_check check (amount = round(amount, 2))
) TABLESPACE pg_default;

------ INDEXES ------

create index payments_date_idx on public.payments (date);
create index payments_work_id_idx on public.payments (work_id);
create index payments_category_id_idx on public.payments (category_id);
create index payments_payment_method_id_idx on public.payments (payment_method_id);

