------ RUN PRODUCTION ------

BEGIN;

DO $$
DECLARE
  has_rows boolean;
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'payments' AND column_name = 'supplier_id'
  ) THEN
    EXECUTE 'SELECT EXISTS (SELECT 1 FROM public.payments WHERE supplier_id IS NOT NULL)' INTO has_rows;
    IF has_rows THEN
      RAISE EXCEPTION 'payments tiene filas con supplier_id: migrarlas a payments_suppliers antes de borrar la columna';
    END IF;
  END IF;
END $$;

ALTER TABLE public.payments DROP CONSTRAINT IF EXISTS payments_supplier_id_fkey;
DROP INDEX IF EXISTS payments_supplier_id_idx;
ALTER TABLE public.payments DROP COLUMN IF EXISTS supplier_id;

COMMIT;
