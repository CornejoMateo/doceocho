------- Voucher types table ------

create table public.voucher_types (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  name text not null,
  is_active boolean not null default true,
  constraint voucher_types_pkey primary key (id),
  constraint voucher_types_name_length_check check (char_length(trim(name)) > 0 and char_length(name) <= 60),
  constraint voucher_types_name_trimmed_check check (name = trim(name))
) TABLESPACE pg_default;

------ INDEXES ------

create unique index voucher_types_name_unique_idx on public.voucher_types (lower(trim(name)));

------ RLS ------

ALTER TABLE public.voucher_types ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public select voucher_types"
ON public.voucher_types
FOR SELECT
TO authenticated
USING (
    EXISTS (
        SELECT 1
        FROM public.users u
        WHERE u.uid_user = auth.uid()
            AND u.role = 'Admin'
    )
);

