------ Channel files ------
-- File attachments per chat channel, accessed from the channel members dialog.

CREATE TABLE IF NOT EXISTS public.channel_files (
  id bigint generated by default as identity not null,
  channel_id bigint not null,
  uploaded_by uuid not null,
  file_name text not null,
  storage_path text not null,
  mime_type text null,
  size_bytes bigint not null,
  created_at timestamp with time zone not null default now(),
  constraint channel_files_pkey primary key (id),
  constraint channel_files_storage_path_key unique (storage_path),
  constraint channel_files_channel_id_fkey foreign key (channel_id) references public.channels (id) on update cascade on delete cascade,
  constraint channel_files_uploaded_by_fkey foreign key (uploaded_by) references public.users (uid_user) on update cascade on delete cascade,
  constraint channel_files_file_name_length_check check (char_length(file_name) <= 255),
  constraint channel_files_size_bytes_check check (size_bytes > 0 and size_bytes <= 10485760)
) TABLESPACE pg_default;

CREATE INDEX IF NOT EXISTS idx_channel_files_channel_created
ON public.channel_files (channel_id, created_at DESC, id DESC);

------ RLS ------

ALTER TABLE public.channel_files ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Channel files select" ON public.channel_files;
CREATE POLICY "Channel files select"
ON public.channel_files FOR SELECT
TO authenticated
USING (
  public.is_channel_member(channel_id, auth.uid())
  OR EXISTS (
    SELECT 1 FROM public.users u
    WHERE u.uid_user = auth.uid() AND public.is_admin_role(u.role)
  )
);

DROP POLICY IF EXISTS "Channel files insert" ON public.channel_files;
CREATE POLICY "Channel files insert"
ON public.channel_files FOR INSERT
TO authenticated
WITH CHECK (
  uploaded_by = auth.uid()
  AND (
    public.is_channel_member(channel_id, auth.uid())
    OR EXISTS (
      SELECT 1 FROM public.users u
      WHERE u.uid_user = auth.uid() AND public.is_admin_role(u.role)
    )
  )
);

DROP POLICY IF EXISTS "Channel files delete" ON public.channel_files;
CREATE POLICY "Channel files delete"
ON public.channel_files FOR DELETE
TO authenticated
USING (
  uploaded_by = auth.uid()
  OR EXISTS (
    SELECT 1 FROM public.users u
    WHERE u.uid_user = auth.uid() AND public.is_admin_role(u.role)
  )
);

CREATE OR REPLACE FUNCTION public.safe_bigint(value text)
RETURNS bigint
LANGUAGE plpgsql
IMMUTABLE
SET search_path = public, pg_catalog
AS $$
BEGIN
  RETURN value::bigint;
EXCEPTION WHEN others THEN
  RETURN NULL;
END;
$$;

