------ HOLIDAY WORK DAYS ------
-- National holidays come from an external API, so they are not stored here.
-- This table only keeps the holidays an admin decided to work anyway.
-- No hours means the regular weekly schedule applies; with hours, only that range.

create table public.holiday_work_days (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  date date not null,
  start_time time without time zone null,
  end_time time without time zone null,
  note text null,
  constraint holiday_work_days_pkey primary key (id),
  constraint holiday_work_days_date_key unique (date),
  constraint holiday_work_days_time_check check (
    (start_time is null and end_time is null)
    or (start_time is not null and end_time is not null and end_time > start_time)
  )
) TABLESPACE pg_default;

------ RLS ------
-- Everyone sees which holidays are worked; only admins change it.
-- The public booking API reads it with the service role.

ALTER TABLE public.holiday_work_days ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Holiday work days select"
ON public.holiday_work_days
FOR SELECT
TO authenticated
USING (true);

CREATE POLICY "Holiday work days insert"
ON public.holiday_work_days
FOR INSERT
TO authenticated
WITH CHECK (
    EXISTS (
        SELECT 1 FROM public.users u
        WHERE u.uid_user = auth.uid() AND u.role = 'Admin'
    )
);

CREATE POLICY "Holiday work days update"
ON public.holiday_work_days
FOR UPDATE
TO authenticated
USING (
    EXISTS (
        SELECT 1 FROM public.users u
        WHERE u.uid_user = auth.uid() AND u.role = 'Admin'
    )
)
WITH CHECK (
    EXISTS (
        SELECT 1 FROM public.users u
        WHERE u.uid_user = auth.uid() AND u.role = 'Admin'
    )
);

CREATE POLICY "Holiday work days delete"
ON public.holiday_work_days
FOR DELETE
TO authenticated
USING (
    EXISTS (
        SELECT 1 FROM public.users u
        WHERE u.uid_user = auth.uid() AND u.role = 'Admin'
    )
);
