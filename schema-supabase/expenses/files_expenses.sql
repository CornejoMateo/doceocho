CREATE TABLE IF NOT EXISTS public.files_expenses (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  storage_path text not null,
  expense_id bigint not null,
  file_name text null,
  description text null,
  constraint files_expenses_pkey primary key (id),
  constraint files_expenses_storage_path_key unique (storage_path),
  constraint files_expenses_expense_id_fkey foreign key (expense_id) references public.expenses (id) on update cascade on delete cascade,
  constraint files_expenses_description_length_check check (description is null or char_length(description) <= 200)
) TABLESPACE pg_default;

------ INDEXES ------

CREATE INDEX IF NOT EXISTS files_expenses_expense_id_idx ON public.files_expenses (expense_id);

------ RLS ------

ALTER TABLE public.files_expenses ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public select files_expenses" ON public.files_expenses;
CREATE POLICY "Public select files_expenses"
ON public.files_expenses
FOR SELECT
TO authenticated
USING (
    EXISTS (
        SELECT 1
        FROM public.users u
        WHERE u.uid_user = auth.uid()
            AND public.is_admin_role(u.role)
    )
);

