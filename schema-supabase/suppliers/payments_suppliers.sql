------ RPC: delete a payment and its files atomically ------
CREATE OR REPLACE FUNCTION public.delete_payment_supplier(p_id bigint)
RETURNS text[]
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
  v_file_paths text[];
  v_deleted_id bigint;
BEGIN
  WITH deleted AS (
    DELETE FROM public.files_payments_suppliers
    WHERE payment_supplier_id = p_id
    RETURNING storage_path
  )
  SELECT array_agg(storage_path) INTO v_file_paths FROM deleted;

  DELETE FROM public.payments_suppliers
  WHERE id = p_id
  RETURNING id INTO v_deleted_id;

  IF v_deleted_id IS NULL THEN
    RAISE EXCEPTION 'No se pudo eliminar el pago (no existe o no tenés permisos)';
  END IF;

  RETURN COALESCE(v_file_paths, ARRAY[]::text[]);
END;
$$;

REVOKE ALL ON FUNCTION public.delete_payment_supplier(bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.delete_payment_supplier(bigint) TO authenticated;

