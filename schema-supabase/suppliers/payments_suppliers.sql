------- Payments suppliers table ------
-- CREATE TABLE/INDEX: solo instalaciones nuevas.

create table public.payments_suppliers (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  paid_date date not null default current_date,
  amount_ars numeric not null,
  receipt_number text null,
  work_id bigint null,
  category_id bigint null,
  kind text not null default 'payment',
  bank_account_id bigint null,
  payment_method_id bigint null,
  purchase_supplier_id bigint not null,
  notes text null,
  constraint payments_suppliers_pkey primary key (id),
  constraint payments_suppliers_kind_check check (kind = 'payment'),
  constraint payments_suppliers_bank_account_id_fkey foreign key (bank_account_id) references public.bank_accounts (id) on update cascade on delete set null,
  constraint payments_suppliers_payment_method_id_fkey foreign key (payment_method_id) references public.payment_methods (id) on update cascade on delete set null,
  constraint payments_suppliers_purchase_supplier_id_fkey foreign key (purchase_supplier_id) references public.purchases_suppliers (id) on update cascade on delete restrict,
  constraint payments_suppliers_work_id_fkey foreign key (work_id) references public.works (id) on delete set null,
  constraint payments_suppliers_category_id_kind_fkey foreign key (category_id, kind) references public.cash_flow_categories (id, kind) on delete set null,
  constraint payments_suppliers_amount_ars_check check (amount_ars > 0),
  constraint payments_suppliers_amount_ars_decimals_check check (amount_ars = round(amount_ars, 2)),
  constraint payments_suppliers_notes_length_check check (notes is null or char_length(notes) <= 2000),
  constraint payments_suppliers_receipt_number_length_check check (receipt_number is null or char_length(receipt_number) <= 60)
) TABLESPACE pg_default;

