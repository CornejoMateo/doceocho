------- Fixed expense payments table ------

create table public.fixed_expense_payments (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  fixed_expense_id bigint not null,
  paid_date date not null default current_date,
  period date not null,
  net_amount numeric not null,
  iva_percent numeric not null default 0,
  iva_amount numeric not null,
  total_amount numeric not null,
  payment_method_id bigint not null,
  bank_account_id bigint null,
  constraint fixed_expense_payments_pkey primary key (id),
  constraint fixed_expense_payments_fixed_expense_id_fkey foreign key (fixed_expense_id) references public.fixed_expenses (id) on delete restrict,
  constraint fixed_expense_payments_payment_method_id_fkey foreign key (payment_method_id) references public.payment_methods (id) on delete restrict,
  constraint fixed_expense_payments_bank_account_id_fkey foreign key (bank_account_id) references public.bank_accounts (id) on delete set null,
  constraint fixed_expense_payments_period_first_day_check check (extract(day from period) = 1),
  constraint fixed_expense_payments_net_amount_check check (net_amount >= 0),
  constraint fixed_expense_payments_iva_percent_check check (iva_percent in (0, 10.5, 21, 27)),
  constraint fixed_expense_payments_iva_amount_check check (iva_amount >= 0),
  constraint fixed_expense_payments_total_amount_check check (total_amount >= 0),
  constraint fixed_expense_payments_total_amount_sum_check check (total_amount = net_amount + iva_amount),
  constraint fixed_expense_payments_fixed_expense_id_period_unique unique (fixed_expense_id, period)
) TABLESPACE pg_default;

------ INDEXES ------

create index fixed_expense_payments_period_idx on public.fixed_expense_payments (period);
create index fixed_expense_payments_fixed_expense_id_idx on public.fixed_expense_payments (fixed_expense_id);

