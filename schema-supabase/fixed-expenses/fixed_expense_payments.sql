------ RPC: register a payment and flip is_paid only for the current ART month ------

CREATE OR REPLACE FUNCTION public.mark_fixed_expense_paid(
  p_fixed_expense_id bigint,
  p_paid_date date,
  p_period date,
  p_net_amount numeric,
  p_iva_percent numeric,
  p_payment_method_id bigint,
  p_bank_account_id bigint DEFAULT NULL
)
RETURNS SETOF public.fixed_expense_payments
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
  v_iva_amount numeric;
  v_total_amount numeric;
  v_current_month date := date_trunc('month', (now() AT TIME ZONE 'America/Argentina/Buenos_Aires'))::date;
BEGIN
  IF extract(day from p_period) <> 1 THEN
    RAISE EXCEPTION 'El período debe ser el primer día del mes';
  END IF;

  v_iva_amount := round(p_net_amount * p_iva_percent / 100, 2);
  v_total_amount := p_net_amount + v_iva_amount;

  RETURN QUERY
  INSERT INTO public.fixed_expense_payments (
    fixed_expense_id,
    paid_date,
    period,
    net_amount,
    iva_percent,
    iva_amount,
    total_amount,
    payment_method_id,
    bank_account_id
  )
  VALUES (
    p_fixed_expense_id,
    p_paid_date,
    p_period,
    p_net_amount,
    p_iva_percent,
    v_iva_amount,
    v_total_amount,
    p_payment_method_id,
    p_bank_account_id
  )
  RETURNING *;

  IF p_period = v_current_month THEN
    UPDATE public.fixed_expenses fe
    SET is_paid = true
    WHERE fe.id = p_fixed_expense_id;
  END IF;
END;
$$;

REVOKE ALL ON FUNCTION public.mark_fixed_expense_paid(bigint, date, date, numeric, numeric, bigint, bigint) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.mark_fixed_expense_paid(bigint, date, date, numeric, numeric, bigint, bigint) TO authenticated;

------ RPC: delete the current ART month payment and flip is_paid back to false ------

CREATE OR REPLACE FUNCTION public.unmark_fixed_expense_paid(p_fixed_expense_id bigint)
RETURNS SETOF public.fixed_expense_payments
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
  v_current_month date := date_trunc('month', (now() AT TIME ZONE 'America/Argentina/Buenos_Aires'))::date;
BEGIN
  RETURN QUERY
  DELETE FROM public.fixed_expense_payments fep
  WHERE fep.fixed_expense_id = p_fixed_expense_id
    AND fep.period = v_current_month
  RETURNING fep.*;

  UPDATE public.fixed_expenses fe
  SET is_paid = false
  WHERE fe.id = p_fixed_expense_id;
END;
$$;

REVOKE ALL ON FUNCTION public.unmark_fixed_expense_paid(bigint) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.unmark_fixed_expense_paid(bigint) TO authenticated;
