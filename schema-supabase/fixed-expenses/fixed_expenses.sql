------ RESET is_paid ON THE 1ST OF EACH MONTH (ART) ------

create or replace function public.reset_fixed_expenses_paid()
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.fixed_expenses set is_paid = false where is_paid = true;
end;
$$;

REVOKE ALL ON FUNCTION public.reset_fixed_expenses_paid() FROM PUBLIC, anon, authenticated;

-- cron runs in UTC; 03:00 UTC = 00:00 ART (UTC-3), 1st of month
SELECT cron.schedule(
  'reset-fixed-expenses-paid',
  '0 3 1 * *',
  $$SELECT public.reset_fixed_expenses_paid();$$
);
