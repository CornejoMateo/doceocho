------- Fixed expenses table ------

create table public.fixed_expenses (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  category_id bigint not null,
  kind text not null default 'fixed_expense',
  amount numeric not null,
  description text not null,
  is_active boolean not null default true,
  is_paid boolean not null default false,
  constraint fixed_expenses_pkey primary key (id),
  constraint fixed_expenses_kind_check check (kind = 'fixed_expense'),
  constraint fixed_expenses_amount_positive_check check (amount > 0),
  constraint fixed_expenses_description_length_check check (char_length(description) between 1 and 200),
  constraint fixed_expenses_description_trimmed_check check (description = trim(description)),
  constraint fixed_expenses_category_id_kind_fkey foreign key (category_id, kind) references public.cash_flow_categories (id, kind) on delete restrict
) TABLESPACE pg_default;

