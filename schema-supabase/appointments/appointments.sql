------ SETTINGS ------
-- Single row (id = 1) with the public booking configuration.

create table public.appointment_settings (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  -- One entry per weekday, indexed 0 = domingo ... 6 = sábado:
  -- [{ "enabled": true, "start": "09:00", "end": "18:00" }, ...]
  weekly_schedule jsonb not null default '[]'::jsonb,
  slot_duration_minutes bigint not null default 60,
  -- How far in advance a client must book, and how far ahead the calendar goes.
  min_notice_hours bigint not null default 24,
  max_days_ahead bigint not null default 30,
  -- Turns the public page on and off without deleting anything.
  is_public_enabled boolean not null default true,
  -- Event type used when an accepted appointment becomes a calendar event.
  event_type_id bigint null,
  constraint appointment_settings_pkey primary key (id),
  constraint appointment_settings_event_type_id_fkey foreign KEY (event_type_id) references events_types (id) on update CASCADE on delete set null
) TABLESPACE pg_default;

